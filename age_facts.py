_COLUMNS = {"es": (2, 4), "en": (3, 5)}  # (fact, joke) column of FACTS per language


def historical_entries(age, language=DEFAULT_LANGUAGE):
    """[(fact, joke)] of the historical facts that apply to the age, in the given language."""
    fact_column, joke_column = _COLUMNS.get(language, _COLUMNS[DEFAULT_LANGUAGE])
    return [(entry[fact_column].replace("{age}", str(age)), entry[joke_column])
            for entry in FACTS if entry[0] <= age <= entry[1]]


def historical_facts(age, language=DEFAULT_LANGUAGE):
    """Facts about people/records at exactly this age (or range of ages)."""
    return [fact for fact, _ in historical_entries(age, language)]


