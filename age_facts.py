def format_number(number, language, decimals=0):
    """1234567.8 -> '1.234.568' (es) / '1,234,568' (en)"""
    text = f"{number:,.{decimals}f}"
    if language == "es":
        text = text.replace(",", "\x00").replace(".", ",").replace("\x00", ".")
    return text


def life_values(age, language=DEFAULT_LANGUAGE, birth_date=None, today=None):
    """Numbers derived from the exact birth date (or from the age when it isn't given), already formatted."""
    if birth_date is not None and today is not None:
        days = (today - birth_date).days
    else:
        days = round(age * 365.2425)
    number = lambda value, decimals=0: format_number(value, language, decimals)  # noqa: E731
    return {
        "days": number(days), "weeks": number(days // 7), "months": number(age * 12),
        "hours": number(days * 24), "minutes": number(days * 24 * 60), "seconds": number(days * 86400),
        "orbits": number(age), "km": number(age * EARTH_ORBIT_KM_MILLIONS),
        "moon": number(days / MOON_ORBIT_DAYS, 1), "mars": number(days / MARS_YEAR_DAYS, 1),
        "mercury": number(days / MERCURY_YEAR_DAYS), "jupiter": number(days / JUPITER_YEAR_DAYS, 1),
    }


def calculated_facts(age, language=DEFAULT_LANGUAGE, birth_date=None, today=None):
    values = life_values(age, language, birth_date, today)
    return [templates.get(language, templates[DEFAULT_LANGUAGE]).format(**values)
            for minimum, templates in CALCULATED if age >= minimum]


def facts_for_age(age, language=DEFAULT_LANGUAGE, birth_date=None, today=None):
    """Every fact for the age: historical ones followed by the calculated ones."""
    return historical_facts(age, language) + calculated_facts(age, language, birth_date, today)
